#!/usr/bin/env python3
"""Track module build status and regenerate modules-src/PROGRESS.md.

  python3 modules-src/tools/progress.py                       # regenerate PROGRESS.md
  python3 modules-src/tools/progress.py set <course> <NN> <status> [note]
  python3 modules-src/tools/progress.py next [n]              # print the next n modules to build

Statuses: todo → building → built (passes check.mjs) → live (deployed + prod-tested); or blocked.
Status lives in each course.json ("status", "note"); PROGRESS.md is generated from it.
"""
import json, sys, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPO = ROOT.parent
ORDER = ["mhf4u", "mcv4u", "mdm4u", "sch4u", "sbi4u", "hfa4u", "eng4u"]  # build order
ICON = {"todo": "·", "building": "…", "built": "◐", "live": "✓", "blocked": "✗"}


def load(c):
    return json.loads((ROOT / "courses" / c / "course.json").read_text())


def save(c, d):
    (ROOT / "courses" / c / "course.json").write_text(json.dumps(d, indent=1, ensure_ascii=False) + "\n")


def status(m):
    return m.get("status", "todo")


def regenerate():
    lines = ["# Interactive modules: build progress", "",
             "Generated by `modules-src/tools/progress.py` from each `course.json`. Don't edit by hand.", "",
             "Legend: ✓ live (deployed + prod-tested) · ◐ built, not yet live · … building · · to do · ✗ blocked", "",
             f"Build order: {' → '.join(c.upper() for c in ORDER)}", ""]
    total = {k: 0 for k in ICON}
    rows = []
    for c in ORDER:
        d = load(c)
        counts = {k: 0 for k in ICON}
        for m in d["modules"]:
            counts[status(m)] += 1
            total[status(m)] += 1
        rows.append((c, d, counts))
    n = sum(total.values())
    lines += [f"**Overall: {total['live']}/{n} live, {total['built']} built, {total['building']} building, "
              f"{total['blocked']} blocked.** Updated {datetime.date.today().isoformat()}.", "",
              "| Course | Site folder | Live | Built | To do | Blocked |", "|---|---|---:|---:|---:|---:|"]
    for c, d, k in rows:
        lines.append(f"| {d['code']} ({c}) | courses/{d['site']}/modules/ | {k['live']}/{len(d['modules'])} | "
                     f"{k['built']} | {k['todo'] + k['building']} | {k['blocked']} |")
    for c, d, k in rows:
        lines += ["", f"## {d['code']} {d['title']} (`{c}`)", ""]
        for m in d["modules"]:
            note = f" — {m['note']}" if m.get("note") else ""
            lines.append(f"- {ICON[status(m)]} {m['nn']} {m['title']} (`{m['slug']}`, {m['kind']}, "
                         f"site ch{m['siteChapter']}){note}")
    (ROOT / "PROGRESS.md").write_text("\n".join(lines) + "\n")


def set_status(c, nn, st, note=None):
    assert st in ICON, st
    d = load(c)
    for m in d["modules"]:
        if m["nn"] == nn.zfill(2):
            m["status"] = st
            if note is not None:
                m["note"] = note
            elif st == "live":
                m.pop("note", None)
            save(c, d)
            regenerate()
            return
    raise SystemExit(f"{c} {nn}: no such module")


def nxt(k):
    out = []
    for c in ORDER:
        for m in load(c)["modules"]:
            if status(m) == "todo":
                out.append(f"{c}:{m['nn']}:{m['slug']}")
    print("\n".join(out[:k]))


if __name__ == "__main__":
    a = sys.argv[1:]
    if not a:
        regenerate()
    elif a[0] == "set":
        set_status(a[1], a[2], a[3], a[4] if len(a) > 4 else None)
    elif a[0] == "next":
        nxt(int(a[1]) if len(a) > 1 else 5)
